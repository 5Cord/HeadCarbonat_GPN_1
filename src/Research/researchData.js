// Для АПИШКИ
export const prepareResearchDataForAPI = (teamId, luId, purchasedWorks, mobilizedWorks) => {
  return {
    teamId,
    luId,
    purchasedWorks: purchasedWorks.map(work => ({
      workId: work.id,
      cost: work.cost,
      purchasedAt: new Date().toISOString()
    })),
    mobilizedWorks: mobilizedWorks.map(work => ({
      workId: work.id,
      mobilizationCost: work.cost,
      mobilizedAt: new Date().toISOString()
    })),
    totalSpent: [
      ...purchasedWorks.map(w => w.cost),
      ...mobilizedWorks.map(w => w.cost)
    ].reduce((sum, cost) => sum + cost, 0),
    successRates: calculateSuccessRates(purchasedWorks, mobilizedWorks)
  };
};

export const calculateSuccessRates = (purchasedWorks, mobilizationWorks) => {
  const rates = {};

  mobilizationWorks.forEach(mobWork => {
    let totalRate = 0;

    purchasedWorks.forEach(work => {
      const rate = work.successRates[mobWork.id] || 0;
      totalRate += rate;
    });

    rates[mobWork.id] = Math.min(totalRate, 95);
  });

  return rates;
};